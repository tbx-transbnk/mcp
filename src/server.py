# sid -> (last used, Session); idle past the refresh lifetime means no live token can still reach it.
_user_sessions: dict[str, tuple[float, Session]] = {}


def _prune_user_sessions() -> None:
    cutoff = time.time() - _REFRESH_TOKEN_TTL
    for sid, (last_used, session) in list(_user_sessions.items()):
        if last_used < cutoff or session.is_signed_out:
            _user_sessions.pop(sid, None)


def _mark_trusthub_signed_out(sid: str, email: str) -> None:
    """Session.on_signed_out hook for TrustHub-OAuth logins: no password to relogin
    with, so evict the Session and kill every lms-mcp token from that login - the
    next call gets a real 401, which is what actually makes Claude prompt reconnect."""
    _logger.warning("TrustHub refresh failed for %s (session %s) - signing out", email, sid)
    _user_sessions.pop(sid, None)
    if _oauth_provider is None:
        return
    try:
        anyio.from_thread.run(_oauth_provider.revoke_session, sid)
    except RuntimeError:
        # Not running inside the worker-thread portal FastMCP sets up for sync tool
        # calls (e.g. called from the event loop itself) - the Session is still
        # evicted above, so the next get_session() at least won't reuse a dead one.
        _logger.warning("could not revoke lms-mcp tokens for %s outside a worker thread", email)
    except (RedisError, OSError) as exc:
        # Session is already evicted, so leftover tokens hit "reconnect"; never let host:port reach the tool caller.
        _logger.error("could not revoke lms-mcp tokens for %s (session %s): %s", email, sid, type(exc).__name__)


def get_session() -> Session:
    # Keyed by the bearer's own sid so it only reaches the session its own login made; missing means "reconnect".
    token = get_access_token()
    claims = (token.claims or {}) if token else {}
    sid = claims.get("sid")
    if not sid:
        raise SessionError("not signed in - this connector requires OAuth; reconnect to trigger sign-in")
    _prune_user_sessions()
    entry = _user_sessions.get(sid)
    if entry is None:
        raise SessionError(f"no active TrustHub session for {claims.get('email')} - reconnect the connector")
    _user_sessions[sid] = (time.time(), entry[1])
    return entry[1]


