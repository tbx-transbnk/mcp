class _ForceHTTPSMiddleware(BaseHTTPMiddleware):
    """HSTS only, never redirects - a conditional http->https redirect was tried
    and pulled twice (crash-looped k8s health probes, then infinite-redirected
    real HTTPS traffic) because this ELB/ingress chain doesn't reliably report
    the original scheme. TLS enforcement belongs at that layer, not here."""

    async def dispatch(self, request: Request, call_next):
        response = await call_next(request)
        response.headers["Strict-Transport-Security"] = "max-age=63072000; includeSubDomains"
        return response


def _allowed_origins() -> frozenset[str]:
    """Scheme+host only, derived from the same redirect-URI allowlist /register already enforces."""
    origins = {f"{(p := urlsplit(uri)).scheme}://{p.netloc}" for uri in allowed_redirect_uris()}
    if _oauth_base_url:
        p = urlsplit(_oauth_base_url)
        origins.add(f"{p.scheme}://{p.netloc}")
    return frozenset(origins)


class _OriginValidationMiddleware(BaseHTTPMiddleware):
    """Rejects a browser Origin outside the allowlist; no Origin header (every non-browser client) passes through."""

    async def dispatch(self, request: Request, call_next):
        origin = request.headers.get("origin")
        if origin and origin not in _allowed_origins():
            return PlainTextResponse("Origin not allowed", status_code=403)
        return await call_next(request)


class _RateLimitMiddleware(BaseHTTPMiddleware):
    """Per-IP fixed-window limit, in-process - correct for the single-replica deployment this server already requires.
    # ponytail: unbounded dict growth across IPs, move to an LRU/TTL cache if that ever matters."""

    _WINDOW_SECONDS = 60

    def __init__(self, app) -> None:
        super().__init__(app)
        self._hits: dict[str, tuple[float, int]] = {}
        self._limit = int(os.environ.get("LMS_MCP_RATE_LIMIT_PER_MINUTE", "120"))

    async def dispatch(self, request: Request, call_next):
        client_ip = request.client.host if request.client else "unknown"
        now = time.time()
        window_start, count = self._hits.get(client_ip, (now, 0))
        if now - window_start >= self._WINDOW_SECONDS:
            window_start, count = now, 0
        count += 1
        self._hits[client_ip] = (window_start, count)
        if count > self._limit:
            return PlainTextResponse("Too many requests", status_code=429)
        return await call_next(request)


def serve() -> None:
    # OAuth is the only sign-in path, and it only exists over HTTP - there is nothing to serve without it.
    if not _oauth_provider:
        raise SystemExit("LMS_MCP_OAUTH_BASE_URL is not set - lms-mcp only runs as an OAuth-protected HTTP connector")
    # Some deployments isolate Redis at the network layer instead of with AUTH (e.g. a
    # headless Service reachable only from this pod's namespace) - LMS_MCP_ALLOW_UNAUTHENTICATED_REDIS
    # is that deployment's explicit, visible opt-in, not a silent fallback.
    if (
        os.environ.get("REDIS_HOST")
        and not os.environ.get("REDIS_PASSWORD")
        and os.environ.get("LMS_MCP_ALLOW_UNAUTHENTICATED_REDIS") != "1"
    ):
        raise SystemExit(
            "REDIS_HOST is set without REDIS_PASSWORD - refusing to keep OAuth state in an "
            "unauthenticated Redis. Set REDIS_PASSWORD, or set "
            "LMS_MCP_ALLOW_UNAUTHENTICATED_REDIS=1 if this Redis is already isolated at the network layer."
        )
    # Without a handler, lastResort drops the lms_mcp INFO security events.
    logging.basicConfig(level=logging.WARNING)
    _logger.setLevel(logging.INFO)
    host = os.environ.get("LMS_MCP_HOST", "0.0.0.0")
    port = int(os.environ.get("PORT") or os.environ.get("LMS_MCP_PORT", "8080"))
    # Only enforced over https - local (http://localhost) must keep working unforced.
    https_only = _oauth_base_url.startswith("https://")
    middleware = [Middleware(_OriginValidationMiddleware), Middleware(_RateLimitMiddleware)]
    if https_only:
        middleware.append(Middleware(_ForceHTTPSMiddleware))
    mcp.run(transport="http", host=host, port=port, middleware=middleware)


def main() -> None:
    serve()


if __name__ == "__main__":
    main()
