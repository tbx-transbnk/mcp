@mcp.custom_route("/login", methods=["GET"])
async def login_page(request: Request) -> HTMLResponse:
    """Shows the client-identity consent notice, then hands off to TrustHub's own hosted sign-in form."""
    request_id = request.query_params.get("request_id")
    if not request_id or _oauth_provider is None:
        return HTMLResponse(
            "Browser sign-in requires a connector request from Claude - there's nothing to do here on its own.",
            status_code=400,
        )
    if not trusthub_oauth.enabled():
        return HTMLResponse(
            "This deployment isn't configured for TrustHub sign-in "
            "(TRUSTHUB_OAUTH_CLIENT_ID, TRUSTHUB_OAUTH_CLIENT_SECRET, or "
            "TRUSTHUB_LOGIN_URL is not set).",
            status_code=500,
        )
    pending = await _oauth_provider.peek_pending_client(request_id)
    if pending is None:
        return HTMLResponse("Invalid or expired sign-in link - reconnect from Claude.", status_code=400)
    browser = request.cookies.get(BROWSER_COOKIE)
    if not await _oauth_provider.browser_matches(request_id, browser):
        _logger.warning("/login rejected: browser-binding cookie mismatch")
        return HTMLResponse(_BROWSER_MISMATCH, status_code=403)
    page = _TRUSTHUB_CONSENT_HTML.format(
        client_name=html.escape(pending["client_name"]),
        unverified_badge="" if pending["verified"] else _UNVERIFIED_BADGE,
        destination=html.escape(pending["destination"]),
        disclaimer=_disclaimer_html(html.escape(pending["client_name"])),
        request_id=html.escape(request_id),
        csrf_token=_oauth_provider.csrf_token(request_id, browser),
    )
    response = HTMLResponse(page)
    response.headers["Cache-Control"] = "no-store"
    response.headers["X-Frame-Options"] = "DENY"
    return response


@mcp.custom_route("/login/continue", methods=["POST"])
async def login_continue(request: Request) -> HTMLResponse | RedirectResponse:
    """The consent form's POST - needs the browser-binding cookie and its CSRF token, then starts the PKCE redirect."""
    form = await request.form()
    request_id = form.get("request_id")
    csrf = form.get("csrf_token")
    if not isinstance(request_id, str) or not isinstance(csrf, str) or _oauth_provider is None or not trusthub_oauth.enabled():
        return HTMLResponse("Invalid request.", status_code=400)
    pending = await _oauth_provider.peek_pending_client(request_id)
    if pending is None:
        return HTMLResponse("Invalid or expired sign-in link - reconnect from Claude.", status_code=400)
    browser = request.cookies.get(BROWSER_COOKIE)
    if not await _oauth_provider.browser_matches(request_id, browser) or not secrets.compare_digest(
        csrf, _oauth_provider.csrf_token(request_id, browser)
    ):
        _logger.warning("/login/continue rejected: browser-binding cookie or CSRF token mismatch")
        return HTMLResponse(_BROWSER_MISMATCH, status_code=403)
    if form.get("accept_disclaimer") != "on":
        # The checkbox disabling the button is client-side UX only - enforce the real gate here.
        return HTMLResponse("You must accept the data-sharing disclaimer to connect.", status_code=400)
    redirect_uri = f"{_oauth_base_url.rstrip('/')}/callback"
    consent_content = _disclaimer_plain_text(pending["client_name"])
    url, state = await _trusthub_pending.start(request_id, redirect_uri, consent=True, consent_content=consent_content)
    resp = RedirectResponse(url, status_code=303)  # 303 so the browser GETs TrustHub instead of re-POSTing the form
    # httpOnly, bound to this browser - the callback rejects any state it didn't set here.
    resp.set_cookie(_STATE_COOKIE, state, httponly=True, secure=True, samesite="lax", max_age=600, path="/callback")
    return resp


