def _exchange_and_bootstrap(
    master: str, lms: str, code: str, verifier: str, redirect_uri: str, sid: str
) -> tuple[str, Session]:
    """The blocking part of /callback (network calls to master) - run via
    anyio.to_thread.run_sync so a slow/unreachable master doesn't stall the whole
    event loop while one user is signing in."""
    client = httpx.Client(timeout=30.0)
    try:
        access_token, _expires_in = trusthub_oauth.exchange_code(master, code, verifier, redirect_uri, client)
        email = _decode_jwt(access_token).get("email")
        if not email:
            raise SessionError("access token carried no email claim")
        session = Session(
            token=access_token, master_base_url=master, lms_base_url=lms, client=client,
            on_signed_out=lambda: _mark_trusthub_signed_out(sid, email),
        )
        return email, session
    except Exception:
        client.close()
        raise


@mcp.custom_route("/callback", methods=["GET"])
async def trusthub_callback(request: Request) -> HTMLResponse | RedirectResponse:
    """Where TrustHub's hosted /login sends the browser back to. Requires both the
    `state` this process issued and the matching httpOnly cookie - state alone
    doesn't prove the callback came from the browser the redirect was sent to."""
    state = request.query_params.get("state")
    cookie_state = request.cookies.get(_STATE_COOKIE)
    if not state or not cookie_state or not secrets.compare_digest(cookie_state, state):
        _logger.warning("/callback rejected: state/cookie mismatch")
        return HTMLResponse("Sign-in link expired or already used - go back and reconnect.", status_code=400)
    pending = await _trusthub_pending.consume(state)
    if pending is None:
        return HTMLResponse("Sign-in link expired or already used - go back and reconnect.", status_code=400)
    error = request.query_params.get("error")
    if error:
        return HTMLResponse(
            f"Sign-in failed ({html.escape(error)}) - go back to Claude and reconnect.", status_code=400
        )
    code = request.query_params.get("code")
    if not code:
        return HTMLResponse("Sign-in failed: no authorization code received.", status_code=400)
    master, lms = os.environ.get("MASTER_BASE_URL", ""), os.environ.get("LMS_BASE_URL", "")
    sid = secrets.token_urlsafe(32)
    try:
        email, candidate = await anyio.to_thread.run_sync(
            _exchange_and_bootstrap, master, lms, code, pending["verifier"], pending["redirect_uri"], sid
        )
    except (RuntimeError, SessionError, httpx.HTTPError, ValueError):
        _logger.exception("TrustHub OAuth code exchange failed")
        return HTMLResponse(
            "Sign-in failed - the link may have expired or already been used. Go back to Claude and reconnect.",
            status_code=400,
        )
    _prune_user_sessions()
    _user_sessions[sid] = (time.time(), candidate)
    if _oauth_provider is None:
        response: HTMLResponse | RedirectResponse = HTMLResponse("Connected.")
    else:
        redirect = await _oauth_provider.complete_authorization(pending["request_id"], email, sid)
        if redirect is None:
            _user_sessions.pop(sid, None)
            return HTMLResponse("Sign-in link expired - go back and reconnect.", status_code=400)
        response = RedirectResponse(redirect)
    _logger.info("sign-in complete for %s (session %s)", email, sid)
    response.headers["Cache-Control"] = "no-store"
    response.delete_cookie(_STATE_COOKIE, path="/callback")
    return response


@mcp.tool(title="List Entity/Program Scopes", annotations=ToolAnnotations(read_only_hint=True))
def list_scopes() -> list[dict[str, str]]:
    """List the TrustHub entity/program scopes this token can access.

    Use the returned `handle` as the `scope` argument to any other tool.
    Omitting `scope` means "all scopes".
    """
    session = get_session()
    return [{"handle": s.handle, "entity": s.entity, "program": s.program} for s in session.scopes]


